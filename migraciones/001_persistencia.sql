CREATE SCHEMA IF NOT EXISTS tesoriq;

CREATE TABLE IF NOT EXISTS tesoriq.usuarios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL,
    nombre text NOT NULL,
    password_hash text NOT NULL,
    salt text NOT NULL,
    rol text NOT NULL CHECK (rol IN ('admin', 'usuario')),
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

-- SQLite NOCASE solo ignora diferencias de mayúsculas ASCII.
CREATE UNIQUE INDEX IF NOT EXISTS usuarios_username_nocase
    ON tesoriq.usuarios (translate(username, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz'));

CREATE TABLE IF NOT EXISTS tesoriq.historial (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint NOT NULL REFERENCES tesoriq.usuarios(id) ON DELETE CASCADE,
    id_cierre text NOT NULL,
    payload text NOT NULL,
    creado_en timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    UNIQUE (usuario_id, id_cierre)
);

CREATE INDEX IF NOT EXISTS historial_usuario_fecha
    ON tesoriq.historial (usuario_id, creado_en DESC, id DESC);

REVOKE ALL ON SCHEMA tesoriq FROM PUBLIC;
